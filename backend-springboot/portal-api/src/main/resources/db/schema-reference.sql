-- portal-api database schema (reference only).
-- Hibernate creates and updates these tables itself (spring.jpa.hibernate.ddl-auto=update); this file is
-- written by hand to match what the JPA entities in com.metrocitypower.portal.persistence produce.
-- The same DDL works on H2 2.2 and PostgreSQL 14+.

-- One submitted case (ApplicationEntity). Flat columns are copied from the start variables for querying;
-- payload_json holds the full latest start/fix variables exactly as they are sent to Camunda.
create table applications (
    application_id        varchar(32)  not null,          -- APP-2026-0001
    submission_id         varchar(64)  not null,          -- browser UUID, F01 double-submit guard
    applicant_name        varchar(200),
    applicant_email       varchar(200),
    applicant_type        varchar(20),                    -- HOME | FACTORY
    site_address          varchar(300),
    region                varchar(20),                    -- NORTH | SOUTH | EAST | WEST | CENTRAL
    meter_id              varchar(40),
    substation_id         varchar(40),
    pv_kw                 float(53),
    inverter_kw           float(53),
    battery_kwh           float(53),
    battery_kw            float(53),
    installer_license_no  varchar(40),
    process_instance_key  bigint,                         -- null until Camunda reports the instance
    status                varchar(20)  not null
        check (status in ('SUBMITTED','ACTIVE','COMPLETED','TERMINATED','UNKNOWN')),
    demo_mode             boolean      not null,
    use_mock_weather      boolean      not null,
    published             boolean      not null,          -- application-submitted accepted by Camunda
    submitted_at          timestamp(6) with time zone not null,
    updated_at            timestamp(6) with time zone not null,
    payload_json          text         not null,
    primary key (application_id),
    constraint uk_applications_submission_id unique (submission_id)
);

-- The devices array (DeviceEntity), the input collection of the multi-instance device check.
create table devices (
    id                    bigint generated by default as identity,
    application_id        varchar(32)  not null,
    sort_order            integer      not null,          -- position in the submitted array
    serial_number         varchar(60),
    device_type           varchar(20),                    -- INVERTER | BATTERY
    model                 varchar(100),
    certificate_id        varchar(60),
    primary key (id)
);
create index ix_devices_application_id on devices (application_id);
alter table if exists devices
    add constraint fk_devices_application foreign key (application_id) references applications;

-- Requests the process sent to the applicant (InboxItemEntity); API id is INB-%04d of id.
-- No foreign key: workers may post for cases started before this database existed.
create table inbox_items (
    id                    bigint generated by default as identity,
    application_id        varchar(32)  not null,
    request_type          varchar(40)  not null,          -- FIX_REQUEST, COST_OFFER, DEFECT_FIX, ...
    payload_json          text         not null,
    created_at            varchar(40)  not null,          -- ISO-8601 text as sent by the worker
    answered              boolean      not null,
    answered_at           varchar(40),
    primary key (id)
);
create index ix_inbox_items_application_id on inbox_items (application_id);

-- Alerts from the ops-alert worker (OpsAlertEntity); API id is ALR-%04d of id.
create table ops_alerts (
    id                    bigint generated by default as identity,
    application_id        varchar(32),
    process_instance_key  bigint,
    error_code            varchar(60),
    error_message         text,
    at                    varchar(40)  not null,          -- ISO-8601 text as sent by the worker
    primary key (id)
);

-- Audit trail (CaseEventEntity): one row per applicant / ops / worker action.
-- application_id is null for grid-wide events (EMERGENCY, EMERGENCY_LIFTED).
create table case_events (
    id                    bigint generated by default as identity,
    application_id        varchar(32),
    event_type            varchar(30)  not null,          -- name of CaseEventType (SUBMITTED, FIX_SUBMITTED, ...)
    details               text,
    at                    timestamp(6) with time zone not null,
    primary key (id)
);
create index ix_case_events_application_id on case_events (application_id);

-- Named counters (IdCounterEntity). Row 'APP-2026' holds the last number handed out; it is read with
-- SELECT ... FOR UPDATE so parallel submits get different ids and the value survives restarts.
create table id_counters (
    name                  varchar(32)  not null,
    last_value            bigint       not null,
    primary key (name)
);
